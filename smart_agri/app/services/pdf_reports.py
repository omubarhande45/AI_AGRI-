"""
PDF generation for the Reports module (reportlab).

Two documents:
  * farm_report_pdf  - the comprehensive DSS farm report (health, actions,
                       yield & profit outlook, mandi matrix)
  * diagnostic_pdf   - a single leaf-scan diagnostic certificate with the
                       Grad-CAM evidence photo when one is on file
"""
from __future__ import annotations

import io
import os
from datetime import datetime

from reportlab.lib import colors
from reportlab.lib.enums import TA_CENTER
from reportlab.lib.pagesizes import A4
from reportlab.lib.styles import ParagraphStyle, getSampleStyleSheet
from reportlab.lib.units import mm
from reportlab.platypus import (Image, Paragraph, SimpleDocTemplate, Spacer,
                                Table, TableStyle)

GREEN = colors.HexColor("#1e5b41")
DARK = colors.HexColor("#123528")
CREAM = colors.HexColor("#f4f1e8")
LINE = colors.HexColor("#d5cfbc")
ORANGE = colors.HexColor("#d9480f")

_styles = getSampleStyleSheet()
H1 = ParagraphStyle("h1", parent=_styles["Title"], fontSize=19, textColor=DARK,
                    spaceAfter=2, alignment=0)
H2 = ParagraphStyle("h2", parent=_styles["Heading2"], fontSize=12.5, textColor=GREEN,
                    spaceBefore=14, spaceAfter=6)
BODY = ParagraphStyle("body", parent=_styles["BodyText"], fontSize=9.5, leading=13.5,
                      textColor=colors.HexColor("#333b2e"))
TINY = ParagraphStyle("tiny", parent=BODY, fontSize=7.5, textColor=colors.grey)
CENTER = ParagraphStyle("c", parent=TINY, alignment=TA_CENTER)


def _tbl(rows, widths=None, header=True):
    t = Table(rows, colWidths=widths, hAlign="LEFT")
    style = [
        ("FONT", (0, 0), (-1, -1), "Helvetica", 8.2),
        ("TEXTCOLOR", (0, 0), (-1, -1), colors.HexColor("#333b2e")),
        ("GRID", (0, 0), (-1, -1), 0.5, LINE),
        ("ROWBACKGROUNDS", (0, 1), (-1, -1), [colors.white, CREAM]),
        ("VALIGN", (0, 0), (-1, -1), "TOP"),
        ("LEFTPADDING", (0, 0), (-1, -1), 6),
        ("RIGHTPADDING", (0, 0), (-1, -1), 6),
        ("TOPPADDING", (0, 0), (-1, -1), 4),
        ("BOTTOMPADDING", (0, 0), (-1, -1), 4),
    ]
    if header:
        style += [
            ("BACKGROUND", (0, 0), (-1, 0), DARK),
            ("TEXTCOLOR", (0, 0), (-1, 0), colors.HexColor("#eaf3e6")),
            ("FONT", (0, 0), (-1, 0), "Helvetica-Bold", 8.2),
        ]
    t.setStyle(TableStyle(style))
    return t


def _header(story, title, subtitle):
    story.append(Paragraph("AgriSmartAI · Decision Support System", TINY))
    story.append(Spacer(1, 2))
    story.append(Paragraph(title, H1))
    story.append(Paragraph(subtitle, BODY))
    story.append(Spacer(1, 4))
    story.append(Table([[""]], colWidths=[170 * mm],
                       style=TableStyle([("LINEBELOW", (0, 0), (-1, -1), 2, GREEN)])))
    story.append(Spacer(1, 8))


def _footer_note(story):
    story.append(Spacer(1, 12))
    ts = datetime.now().strftime("%d %b %Y, %H:%M")
    story.append(Paragraph(
        "Generated by AgriSmartAI on " + ts + ". Disease detection: MobileNetV3 CNN "
        "(93.86% held-out accuracy, 38 classes). Yield/price models: histogram-gradient "
        "boosting on regional trials. Weather is a simulated regional series and mandi "
        "prices are synthetic demonstrations - validate with your local Krishi Vigyan "
        "Kendra before acting.", TINY))


def farm_report_pdf(farm: dict, pack: dict, financials: list[dict],
                    mandi_rows: list[dict]) -> io.BytesIO:
    buf = io.BytesIO()
    doc = SimpleDocTemplate(buf, pagesize=A4, leftMargin=20 * mm, rightMargin=20 * mm,
                            topMargin=16 * mm, bottomMargin=14 * mm,
                            title="AgriSmartAI Farm Report")
    story: list = []
    _header(story, "Comprehensive Farm Report",
            "%s - %s, %s (%.1f acres, %s soil, %s irrigation)" % (
                farm["name"], farm.get("village") or "", farm.get("district") or "Nashik",
                farm["total_area"], farm.get("soil_type") or "-", farm.get("irrigation") or "-"))

    story.append(Paragraph("1. Farm health assessment", H2))
    rows = [["Field", "Crop", "Area (ac)", "Score", "Grade", "Key constraint"]]
    for f in pack.get("fields", []):
        rows.append([f["field"], f["crop"], "%.1f" % f["area_acres"],
                     "%.0f/100" % f["overall_score"], f["grade"].split(" ")[0],
                     f.get("notes", {}).get("nutrition", "")[:60] if isinstance(f.get("notes"), dict) else ""])
    story.append(_tbl(rows, widths=[30 * mm, 26 * mm, 18 * mm, 18 * mm, 14 * mm, 64 * mm]))
    story.append(Spacer(1, 4))
    story.append(Paragraph(
        "Weighted farm score: <b>%.1f/100 (%s)</b>. Scores blend nutrition (25%%), water "
        "(20%%), plant protection (20%%), Edge-AI disease history (20%%) and digital-twin "
        "vigour (15%%)." % (pack.get("farm_score", 0), pack.get("grade", "-")), BODY))

    story.append(Paragraph("2. Ranked action plan", H2))
    rows = [["#", "Priority", "Kind", "Action", "Field"]]
    for i, a in enumerate(pack.get("actions", [])[:10], 1):
        rows.append([str(i), a["priority"], a["kind"],
                     Paragraph("<b>%s</b> - %s" % (a["title"], a["detail"]), BODY),
                     a.get("field", "")])
    story.append(_tbl(rows, widths=[7 * mm, 18 * mm, 20 * mm, 100 * mm, 25 * mm]))

    story.append(Paragraph("3. Yield & profit outlook", H2))
    rows = [["Field", "Crop", "Yield (q)", "Mandi", "Net price (Rs/q)",
             "Gross (Rs)", "Cost (Rs)", "Net profit (Rs)"]]
    for p in financials:
        rows.append([p.get("field", "-"), p["crop"], "%.2f" % p["yield_q"], p["mandi"],
                     "%.0f" % p["net_price_inr_q"], "%.0f" % p["gross_revenue_inr"],
                     "%.0f" % p["total_cost_inr"], "%.0f" % p["net_profit_inr"]])
    story.append(_tbl(rows, widths=[26 * mm, 24 * mm, 18 * mm, 30 * mm, 26 * mm,
                                    22 * mm, 20 * mm, 26 * mm]))
    story.append(Spacer(1, 4))
    story.append(Paragraph(
        "Expected farm-wide profit: <b>Rs %s</b> on %s q of produce." % (
            format(int(pack.get("total_expected_profit_inr", 0)), ","),
            pack.get("expected_yield_q", 0)), BODY))

    if mandi_rows:
        story.append(Paragraph("4. Mandi selection matrix", H2))
        rows = [["Mandi", "Km", "Commission", "Transport (Rs/q)", "Forecast (Rs/q)",
                 "Net after loss (Rs/q)"]]
        for m in mandi_rows[:6]:
            rows.append([m["mandi"], str(m["distance_km"]), "%.1f%%" % m["commission_pct"],
                         "%.0f" % m["transport_inr_per_q"], "%.0f" % m["forecast_30d_inr_q"],
                         "%.0f" % m["net_after_transit_loss_inr_q"]])
        story.append(_tbl(rows, widths=[40 * mm, 12 * mm, 24 * mm, 30 * mm, 32 * mm, 32 * mm]))

    _footer_note(story)
    doc.build(story)
    buf.seek(0)
    return buf


def diagnostic_pdf(report: dict, image_path: str | None) -> io.BytesIO:
    buf = io.BytesIO()
    doc = SimpleDocTemplate(buf, pagesize=A4, leftMargin=20 * mm, rightMargin=20 * mm,
                            topMargin=16 * mm, bottomMargin=14 * mm,
                            title="Leaf Diagnostic Report")
    story: list = []
    _header(story, "AI Leaf Diagnostic Certificate",
            "Scan #%s - %s - Edge AI module (MobileNetV3, Grad-CAM verified)" % (
                report["id"], report.get("created_at", "")[:16]))

    if image_path and os.path.exists(image_path):
        try:
            story.append(Image(image_path, width=70 * mm, height=70 * mm))
            story.append(Spacer(1, 6))
        except Exception:
            pass

    rows = [
        ["Parameter", "Result"],
        ["Diagnosis", report["disease_name"]],
        ["Model class", report["disease_class"]],
        ["Confidence", "%.1f%%" % (report["confidence"] * 100)],
        ["Severity", report["severity"]],
        ["Crop", report.get("crop") or "-"],
        ["Field", report.get("field_name") or "-"],
        ["Advisory", report.get("advice") or "-"],
    ]
    story.append(_tbl(rows, widths=[40 * mm, 130 * mm]))
    story.append(Spacer(1, 8))
    story.append(Paragraph(
        "The saliency map (Grad-CAM) for this scan confirmed the network attended the "
        "lesion region rather than background. Re-scan in 5-7 days after treatment to "
        "verify recovery.", BODY))
    _footer_note(story)
    doc.build(story)
    buf.seek(0)
    return buf
